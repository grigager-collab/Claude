def num(s):
    s = str(s or '').replace(' ', '').replace('\xa0', '').replace(',', '.')
    return float(s) if s else 0.0


def sku(p): return p['editions'][0]['sku'] if p.get('editions') else p.get('sku', '')


def chars(p):
    """Характеристики товара: {название: [значения]} — у одной характеристики может быть несколько записей."""
    d = {}
    for c in p.get('characteristics') or []:
        for v in str(c['value']).split(SEP):
            v = v.strip()
            if v and v not in d.setdefault(c['title'], []): d[c['title']].append(v)
    return d


def parts(p): return [str(x) for x in json.loads(p.get('partuids') or '[]')]


def target(p, A):
    """Как должно стать: ({характеристика: [значения]}, [пути разделов], [почему])."""
    c, s, pp, why = chars(p), sku(p), parts(p), []
    one = lambda k: (c.get(k) or [''])[0]
    t = {k: list(c.get(k) or []) for k in CHARS}
    # сезон — вопрос 1: шортам «Лето», Winter tale «Зима», остальным «Всесезон»
    season = 'Зима' if 'winter tale' in p['title'].lower() else ('Лето' if SHORTY in pp else 'Всесезон')
    if one('Сезон') == 'Демисезон': why.append('«Демисезон» нет в схеме → «Всесезон»')
    elif season == 'Лето' and one('Сезон') != 'Лето': why.append('шорты → «Лето»')
    t['Сезон'] = [season]
    # подклад — как в схеме
    lin = one('Подклад')
    t['Подклад'] = ['Шёлковый подклад' if lin in ('Шёлк', 'Шёлковый подклад') else 'Без подклада']
    if lin == 'Шёлк': why.append('подклад «Шёлк» → «Шёлковый подклад», как в схеме')
    # стиль — только «Повседневный» / «Спортивный»
    st = one('Стиль')
    if 'повседнев' in p['title'].lower() and st == 'Спортивный':
        st_n = 'Повседневный'; why.append('в названии «повседневный», а стиль стоял «Спортивный»')
    elif st in ('Повседневный', 'Спортивный'): st_n = st
    elif st == 'Деловой': st_n = 'Повседневный'; why.append('«Деловой» нет в схеме → «Повседневный»')
    else:
        v, w = STYLE_FIX[s]
        if v is None: v = one_of(A, '21260503', 'Стиль')
        st_n = v; why.append('стиль был пустой: ' + w)
    t['Стиль'] = [st_n]
    # капсула — «Ватаным» как есть; «Премиум коллекция» — вопрос 5
    if s in PREMIUM and 'Премиум коллекция' not in t['Капсула']:
        t['Капсула'].append('Премиум коллекция'); why.append('+ «Премиум коллекция» (вопрос 5)')
    # коллекция — скрытое свойство: вопрос 2
    new = KOMPLEKTY in pp or (KOSTYUMY_M in pp and one('Цвет') == 'Зелёный')
    old = max([num(e.get('priceold')) for e in p.get('editions') or []] or [0])
    if old: assert s in SALE, (s, p['title'], 'новая скидка — добавить в SALE')
    col = 'Распродажа' if s in SALE else ('Новинка' if new else 'Базовая коллекция')
    t['Коллекция'] = [col]
    # разделы
    cats = [x for x in pp if x != NOVINKI or new]
    if new and NOVINKI not in cats: cats.append(NOVINKI); why.append('в «Новинки»: все комплекты и зелёные костюмы (вопрос 2)')
    if NOVINKI in pp and not new: why.append('из «Новинок» убран: новинки — комплекты и зелёные костюмы (вопрос 2)')
    if s in SOFT and PIDZHAKI not in cats: cats.append(PIDZHAKI); why.append('+ «Мягкие пиджаки»: ' + SOFT[s] + ' (вопрос 3)')
    unknown = [x for x in cats if x not in CAT]
    assert not unknown, (p['title'], unknown)
    return t, [CAT[x] for x in cats], why


def one_of(A, s, k):
    return (chars(next(p for p in A if sku(p) == s)).get(k) or [''])[0]
